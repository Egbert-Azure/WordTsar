/**
 * @class cTUIDebugReport
 *
 * @brief TUI crash debug report generator and system information collector.
 *
 * Qt-free equivalent of the GUI cDebugReport class. Gathers system
 * information via POSIX uname(), locates crash data (core dumps and
 * backtraces), and packages everything into a timestamped ZIP file
 * for bug report submission.
 *
 * @section tui_debugreport_collection Data Collection
 * - System information: CPU architecture, kernel version, OS name
 *   (via POSIX uname() instead of Qt QSysInfo)
 * - Core dump files: searches standard locations and systemd-coredumpctl
 *   on Linux for the most recent crash dump
 * - Backtrace extraction: searches for backtrace files generated by chillout
 *
 * @section tui_debugreport_packaging Report Packaging
 * All collected data is written into a timestamped ZIP archive containing:
 * - debug_report.txt: hardware and OS details
 * - backtrace file (if found)
 * - core dump file (if found)
 *
 * @section tui_debugreport_output Output
 * Since no interactive dialog is available during a terminal crash,
 * all crash information is written to stderr and packaged into a ZIP
 * file. The user is instructed to email the ZIP to the developer.
 *
 * @author Gerald Brandt
 * @copyright GNU Affero General Public License v3.0
 *
 * @see cTUIDebugReport
 */

#include <iostream>
#include <fstream>
#include <filesystem>
